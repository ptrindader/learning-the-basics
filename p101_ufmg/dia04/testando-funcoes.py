def soma(a:int, b:int) -> int:
    total = a + b
    return total

# Cria uma função "soma" que recebe inteiros como
# argumentos e espera (por isso o "->") o retorno
# de um inteiro.
# 
# Ela tem uma variável "total" dentro dela
# que soma os argumentos
# 
# No fim, ela devolve (return) o valor dessa variável
# "total" ao usuário.