# '"for" tipo 1, só com range()')
for i in range(11):
    print(i)
print('\n')

# Por padrão, ele considera
# i = 0 e itera i++.

# '"for" tipo 2, com range tendo começo e fim')
for i in range(0, 11):
    print(i)
print('\n')

# "for" tipo 3, com começo, fim e quanto você quer que ele itere')
for i in range(0, 11, 3):
    print(i)

    